// 방식+시간대에 맞는 출현 풀과 레벨
export function encounterPool(loc: Location, method: Method, night: boolean): Species[] {
  let types = METHOD_TYPES[method].slice();
  if (method === "걷기" || method === "잠복") types = loc.주요타입.slice();
  if (method === "야간" || night) types = Array.from(new Set([...types, ...loc.주요타입, "고스트", "악", "에스퍼"]));
  if (!types.length) types = loc.주요타입.slice();
  let pool = Array.from(SPECIES.values()).filter(
    (s) => s.타입.some((t) => types.includes(t)) && (RARITY_WEIGHT[s.희귀도] ?? 0) > 0
  );
  if (!pool.length) pool = Array.from(SPECIES.values()).filter((s) => (RARITY_WEIGHT[s.희귀도] ?? 0) > 0);
  return pool;
}

export interface Encounter { species: Species; level: number; legend: boolean; }

export function rollEncounter(rng: RNG, loc: Location, method: Method, night: boolean): Encounter {
  const [lo, hi] = loc.레벨;
  let level = rng.int(lo, hi);
  // 현실성: 저렙~고렙이 마구잡이로 섞인다. 가끔 약골/거물이 튀어나온다.
  const r = rng.rand();
  if (r < 0.12) level = Math.max(2, lo - rng.int(2, 6));            // 약골
  else if (r > 0.92) level = Math.min(100, hi + rng.int(8, 22));    // 거물
  else if (r > 0.80) level = Math.min(100, hi + rng.int(2, 8));     // 강한 개체
  if (method === "잠복" || method === "동굴" || method === "등산") level = Math.min(100, level + rng.int(0, 4));

  // 배회 전설 (잠복에서만, 매우 드묾)
  if (method === "잠복" && loc.전설?.length && rng.rand() < 1 / 90) {
    const id = rng.pick(loc.전설);
    if (SPECIES.has(id)) return { species: SPECIES.get(id)!, level: Math.max(level, hi + 8), legend: true };
  }
  // 시그니처 희귀종 (가끔)
  if (loc.희귀종?.length && rng.rand() < (method === "잠복" ? 0.22 : 0.08)) {
    const id = rng.pick(loc.희귀종);
    if (SPECIES.has(id)) return { species: SPECIES.get(id)!, level, legend: false };
  }
  const pool = encounterPool(loc, method, night);
  let weights = pool.map((s) => RARITY_WEIGHT[s.희귀도] ?? 1);
  if (method === "잠복") weights = pool.map((s) => (s.희귀도 === "희귀" || s.희귀도 === "매우희귀" ? 30 : RARITY_WEIGHT[s.희귀도]));
  const species = rng.weighted(pool, weights);
  return { species, level, legend: false };
}
